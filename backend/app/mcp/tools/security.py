import os
import uuid
from typing import Any, Dict
from sqlalchemy.ext.asyncio import AsyncSession

from app.engines.policy.engine import policy_engine
from app.engines.policy.models import ActorContext, DecisionContext, OperationContext
from app.mcp.errors import MCPInvalidInputError, MCPExecutionFailedError
from app.mcp.schemas import MCPContext, ToolExecutionResult
from app.repositories.blueprint_repository import BlueprintRepository
from app.repositories.policy_repository import PolicyRepository


async def execute_get_security_blueprint(
    context: MCPContext,
    arguments: Dict[str, Any],
    db: AsyncSession,
) -> ToolExecutionResult:
    """
    Returns the active Security Blueprint and requirements generated by Step 5.
    """
    raw_pid = arguments.get("project_id")
    if not raw_pid:
        raise MCPInvalidInputError("Missing required parameter 'project_id'.")

    try:
        project_uuid = uuid.UUID(str(raw_pid))
    except (ValueError, TypeError):
        raise MCPInvalidInputError(f"Invalid UUID string for 'project_id': '{raw_pid}'.")

    blueprint_repo = BlueprintRepository(db)
    bp = await blueprint_repo.get_latest_for_project(project_uuid)
    if not bp:
        return ToolExecutionResult(
            status="NOT_FOUND",
            message=f"No active security blueprint found for project '{project_uuid}'.",
            error_code="MCP_RESOURCE_NOT_FOUND",
        )

    # Detailed fetch
    bp_obj = await blueprint_repo.get_by_id(bp.id)
    reqs_data = []
    if bp_obj and bp_obj.requirements:
        for r in bp_obj.requirements:
            reqs_data.append({
                "id": str(r.id),
                "requirement_key": r.requirement_key,
                "title": r.title,
                "description": r.description,
                "category": r.category,
                "severity": r.severity,
                "verification_strategy": r.verification_strategy,
            })

    return ToolExecutionResult(
        status="SUCCESS",
        data={
            "blueprint_id": str(bp_obj.id),
            "version": bp_obj.version,
            "status": bp_obj.status,
            "requirements_count": len(reqs_data),
            "requirements": reqs_data,
        },
        message=f"Retrieved blueprint v{bp_obj.version} with {len(reqs_data)} security requirements.",
        result_reference=str(bp_obj.id),
    )


async def execute_get_security_requirements(
    context: MCPContext,
    arguments: Dict[str, Any],
    db: AsyncSession,
) -> ToolExecutionResult:
    """
    Returns list of active blueprint requirements for the project.
    """
    return await execute_get_security_blueprint(context, arguments, db)


async def execute_check_security_policy(
    context: MCPContext,
    arguments: Dict[str, Any],
    db: AsyncSession,
) -> ToolExecutionResult:
    """
    Invokes the Step 7 Policy Engine deterministically to check policy permissions.
    """
    raw_pid = arguments.get("project_id")
    operation_name = arguments.get("operation", "RUN_SECURITY_SCAN")
    resource = arguments.get("resource", {})

    if not raw_pid:
        raise MCPInvalidInputError("Missing required parameter 'project_id'.")

    try:
        project_uuid = uuid.UUID(str(raw_pid))
    except (ValueError, TypeError):
        raise MCPInvalidInputError(f"Invalid UUID string for 'project_id': '{raw_pid}'.")

    policy_repo = PolicyRepository(db)
    policies = await policy_repo.list_policies_for_project(project_uuid, active_only=True)

    policy_tuples = []
    for pol in policies:
        if pol.versions:
            latest_ver = pol.versions[0]
            policy_tuples.append((pol.name, latest_ver.version, latest_ver.definition))

    actor = ActorContext(
        type="AGENT",
        id=str(context.identity.agent_id),
        name=context.identity.agent_name,
        roles=[context.identity.agent_type, context.identity.trust_level],
    )

    op_context = OperationContext(
        type=operation_name,
        environment=context.metadata.get("environment", "development"),
        resource_type=arguments.get("resource_type"),
        metadata=resource,
    )

    decision_ctx = DecisionContext(
        project_id=str(project_uuid),
        actor=actor,
        operation=op_context,
        environment=context.metadata.get("environment", "development"),
        findings=[],
        verifications=[],
        requirements=[],
    )

    result = policy_engine.evaluate(decision_ctx, policy_tuples)

    return ToolExecutionResult(
        status="SUCCESS",
        data={
            "decision": result.decision.value,
            "reason": result.reason,
            "matched_rules": result.matched_rules,
            "policy_version_ids": result.policy_version_ids,
        },
        message=f"Policy decision evaluated: {result.decision.value}",
        result_reference=result.decision.value,
    )
