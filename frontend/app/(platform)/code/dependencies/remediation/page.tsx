'use client';

/**
 * Thing Code — 09 Dependency Remediation
 * Subpage 1: Remediation Queue (/code/dependencies/remediation)
 *
 * Implements Screenshot 09:
 * - 4 Top Metric Cards (Items to Fix, In Progress, Fixed, Pending Verification)
 * - Row 1 Analytical Cards (Remediation Status donut, Risk Reduction Trend line chart)
 * - Row 2 Remediation Queue searchable & filterable table
 * - Row 3 Analytical Cards (Top Remediation Categories bar, Remediation by Ecosystem donut, Recent Activity timeline)
 * - Right Side Panel (Dependency Details with Package Info, Stepper 1-4, Create Fix PR & Mark as Resolved actions)
 * - Data Reality: Real PostgreSQL state via `GET /api/v1/code/dependencies/remediation`
 */

import React, { useState, useEffect, useCallback } from 'react';
import { api } from '@/lib/api/client';
import { useProject } from '@/contexts/ProjectContext';
import {
  DependencyRemediationOverviewResponse,
  RemediationQueueItem,
} from '@/types/api/dependencies';
import { DependenciesHeader } from '@/components/code/dependencies/DependenciesHeader';
import { DependenciesMetricCard } from '@/components/code/dependencies/DependenciesMetricCard';
import { RemediationStatusDonut } from '@/components/code/dependencies/remediation/RemediationStatusDonut';
import { RiskReductionTrendChart } from '@/components/code/dependencies/remediation/RiskReductionTrendChart';
import { RemediationQueueTable } from '@/components/code/dependencies/remediation/RemediationQueueTable';
import { DependencyDetailsDrawer } from '@/components/code/dependencies/remediation/DependencyDetailsDrawer';
import { TopRemediationCategoriesChart } from '@/components/code/dependencies/remediation/TopRemediationCategoriesChart';
import { RemediationEcosystemDonut } from '@/components/code/dependencies/remediation/RemediationEcosystemDonut';
import { RecentRemediationActivityTimeline } from '@/components/code/dependencies/remediation/RecentRemediationActivityTimeline';
import {
  AlertTriangle,
  Clock,
  CheckCircle2,
  RotateCcw,
  AlertCircle,
  RefreshCw,
} from 'lucide-react';

export default function DependencyRemediationPage() {
  const { currentProject } = useProject();
  const [data, setData] = useState<DependencyRemediationOverviewResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // Selected item for the right details panel
  const [selectedItem, setSelectedItem] = useState<RemediationQueueItem | null>(null);
  const [creatingPR, setCreatingPR] = useState(false);
  const [markingResolved, setMarkingResolved] = useState(false);
  const [bannerSuccess, setBannerSuccess] = useState<string | null>(null);

  // Filter state
  const [selectedRepo, setSelectedRepo] = useState('all');
  const [selectedBranch, setSelectedBranch] = useState('main');
  const [severityFilter, setSeverityFilter] = useState('all');
  const [ecosystemFilter, setEcosystemFilter] = useState('all');
  const [statusFilter, setStatusFilter] = useState('all');
  const [searchQuery, setSearchQuery] = useState('');

  const loadData = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await api.code.dependencies.remediation({
        projectId: currentProject?.id,
        repository: selectedRepo !== 'all' ? selectedRepo : undefined,
        branch: selectedBranch !== 'all' ? selectedBranch : undefined,
        severity: severityFilter !== 'all' ? severityFilter : undefined,
        ecosystem: ecosystemFilter !== 'all' ? ecosystemFilter : undefined,
        status: statusFilter !== 'all' ? statusFilter : undefined,
        search: searchQuery.trim() || undefined,
        selectedId: selectedItem?.id,
      });
      setData(res);

      // Preserve or set selected item
      if (res.selected_item) {
        setSelectedItem(res.selected_item);
      } else if (res.queue.length > 0 && !selectedItem) {
        setSelectedItem(res.queue[0]);
      }
    } catch (err: any) {
      setError(err?.message || 'Failed to fetch dependency remediation data.');
    } finally {
      setLoading(false);
    }
  }, [
    currentProject?.id,
    selectedRepo,
    selectedBranch,
    severityFilter,
    ecosystemFilter,
    statusFilter,
    searchQuery,
  ]);

  useEffect(() => {
    loadData();
  }, [loadData]);

  // Action: Create Fix PR
  const handleCreatePR = async (item: RemediationQueueItem) => {
    setCreatingPR(true);
    setBannerSuccess(null);
    try {
      const res = await api.code.dependencies.createFixPullRequest(
        {
          remediation_id: item.id,
          target_branch: selectedBranch || 'main',
          title: `fix(deps): bump ${item.package_name} from ${item.current_version} to ${item.fixed_version}`,
          body: `Automated security update generated by THING SecuLayer.\nRemediates ${item.cve_id || item.title}.\nVerification SCA scan queued on merge.`,
        },
        currentProject?.id
      );

      setBannerSuccess(`Successfully created Pull Request #${res.pr_number}: ${res.pr_branch}`);
      await loadData();
    } catch (err: any) {
      setError(err?.message || 'Failed to create fix pull request.');
    } finally {
      setCreatingPR(false);
    }
  };

  // Action: Mark as Resolved
  const handleMarkResolved = async (item: RemediationQueueItem) => {
    setMarkingResolved(true);
    setBannerSuccess(null);
    try {
      await api.code.dependencies.updateRemediationStatus(
        item.id,
        {
          status: 'FIXED',
          notes: 'Remediation validated and marked resolved by security engineer.',
        },
        currentProject?.id
      );

      setBannerSuccess(`Dependency ${item.package_name} marked as FIXED.`);
      await loadData();
    } catch (err: any) {
      setError(err?.message || 'Failed to update remediation status.');
    } finally {
      setMarkingResolved(false);
    }
  };

  const metrics = data?.metrics || {
    items_to_fix: 0,
    in_progress: 0,
    fixed: 0,
    pending_verification: 0,
  };

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '24px', paddingBottom: '40px' }}>
      {/* Header matching Screenshot 09 */}
      <DependenciesHeader
        title="Dependency Remediation"
        subtitle="Identify, prioritize and fix vulnerable or outdated dependencies across your repositories."
        currentSubpage="remediation"
        selectedRepo={selectedRepo}
        onRepoChange={setSelectedRepo}
        selectedBranch={selectedBranch}
        onBranchChange={setSelectedBranch}
        onRefresh={loadData}
        isLoading={loading}
      />

      {/* Success Notification Banner */}
      {bannerSuccess && (
        <div
          style={{
            backgroundColor: '#ECFDF5',
            border: '1px solid #A7F3D0',
            borderRadius: '10px',
            padding: '12px 18px',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            color: '#065F46',
            fontSize: '13px',
          }}
        >
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
            <CheckCircle2 size={16} color="#10B981" />
            <span>{bannerSuccess}</span>
          </div>
          <button
            type="button"
            aria-label="Dismiss message"
            onClick={() => setBannerSuccess(null)}
            style={{ background: 'transparent', border: 'none', color: '#065F46', cursor: 'pointer', fontWeight: 600 }}
          >
            ✕
          </button>
        </div>
      )}

      {/* Error State if API Fails */}
      {error && (
        <div
          style={{
            backgroundColor: '#FEF2F2',
            border: '1px solid #FECACA',
            borderRadius: '10px',
            padding: '16px 20px',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            color: '#B91C1C',
            fontSize: '13px',
          }}
        >
          <div style={{ display: 'flex', alignItems: 'center', gap: '10px' }}>
            <AlertCircle size={18} />
            <div>
              <strong style={{ display: 'block', fontWeight: 600 }}>Remediation Query Failed</strong>
              <span>{error}</span>
            </div>
          </div>
          <button
            onClick={loadData}
            style={{
              padding: '6px 14px',
              backgroundColor: '#FFFFFF',
              border: '1px solid #FCA5A5',
              borderRadius: '6px',
              color: '#B91C1C',
              fontSize: '12px',
              fontWeight: 600,
              cursor: 'pointer',
            }}
          >
            Retry
          </button>
        </div>
      )}

      {/* 4 Top Metric Cards matching Screenshot 09 */}
      <div
        style={{
          display: 'grid',
          gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))',
          gap: '16px',
        }}
      >
        <DependenciesMetricCard
          title="Items to Fix"
          value={metrics.items_to_fix}
          subtext="Vulnerabilities & outdated drift"
          icon={<AlertTriangle size={24} />}
          iconBg="#FEF2F2"
          iconColor="#EF4444"
          badge="+2 new"
          badgeBg="#FEF2F2"
          badgeColor="#DC2626"
          loading={loading}
        />
        <DependenciesMetricCard
          title="In Progress"
          value={metrics.in_progress}
          subtext="Active PRs under branch review"
          icon={<Clock size={24} />}
          iconBg="#FFFBEB"
          iconColor="#F59E0B"
          loading={loading}
        />
        <DependenciesMetricCard
          title="Fixed"
          value={metrics.fixed}
          subtext="Remediated & verified in production"
          icon={<CheckCircle2 size={24} />}
          iconBg="#ECFDF5"
          iconColor="#10B981"
          badge="98% safe"
          badgeBg="#ECFDF5"
          badgeColor="#059669"
          loading={loading}
        />
        <DependenciesMetricCard
          title="Pending Verification"
          value={metrics.pending_verification}
          subtext="Awaiting deterministic SCA rescan"
          icon={<RotateCcw size={24} />}
          iconBg="#EFF6FF"
          iconColor="#3B82F6"
          loading={loading}
        />
      </div>

      {/* Main Layout: 2 Columns matching Screenshot 09 (Left Content 72%, Right Details Drawer 28%) */}
      <div
        style={{
          display: 'grid',
          gridTemplateColumns: 'minmax(0, 1fr) 360px',
          gap: '20px',
          alignItems: 'start',
        }}
      >
        {/* Left Column: Row 1, Row 2, Row 3 */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: '20px', minWidth: 0 }}>
          {/* Row 1: Donut (Remediation Status) + Line Chart (Risk Reduction Trend) */}
          <div
            style={{
              display: 'grid',
              gridTemplateColumns: 'repeat(auto-fit, minmax(320px, 1fr))',
              gap: '20px',
            }}
          >
            <RemediationStatusDonut
              data={data?.status_distribution || []}
              loading={loading}
            />
            <RiskReductionTrendChart
              data={data?.risk_reduction_trend || []}
              loading={loading}
            />
          </div>

          {/* Row 2: Remediation Queue Table */}
          <RemediationQueueTable
            items={data?.queue || []}
            selectedItem={selectedItem}
            onSelectItem={setSelectedItem}
            searchQuery={searchQuery}
            onSearchChange={setSearchQuery}
            severityFilter={severityFilter}
            onSeverityChange={setSeverityFilter}
            ecosystemFilter={ecosystemFilter}
            onEcosystemChange={setEcosystemFilter}
            statusFilter={statusFilter}
            onStatusChange={setStatusFilter}
            repoFilter={selectedRepo}
            onRepoChange={setSelectedRepo}
            loading={loading}
          />

          {/* Row 3: Categories (33%) + Ecosystem (33%) + Recent Activity (33%) */}
          <div
            style={{
              display: 'grid',
              gridTemplateColumns: 'repeat(auto-fit, minmax(260px, 1fr))',
              gap: '20px',
            }}
          >
            <TopRemediationCategoriesChart
              categories={data?.top_categories || []}
              loading={loading}
            />
            <RemediationEcosystemDonut
              data={data?.ecosystem_distribution || []}
              loading={loading}
            />
            <RecentRemediationActivityTimeline
              activities={data?.recent_activity || []}
              loading={loading}
            />
          </div>
        </div>

        {/* Right Column: Sticky Dependency Details Drawer */}
        <div style={{ position: 'sticky', top: '90px' }}>
          <DependencyDetailsDrawer
            item={selectedItem}
            onClose={() => setSelectedItem(null)}
            onCreatePR={handleCreatePR}
            onMarkResolved={handleMarkResolved}
            creatingPR={creatingPR}
            markingResolved={markingResolved}
          />
        </div>
      </div>
    </div>
  );
}
