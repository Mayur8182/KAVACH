export interface BreadcrumbStep {
  label: string;
  href?: string;
}

export interface RouteEmptyState {
  title: string;
  description: string;
  actionLabel?: string;
  actionRoute?: string;
}

export interface RouteLoadingState {
  type: 'skeleton-table' | 'skeleton-cards' | 'skeleton-dashboard';
  hint: string;
}

export interface RouteErrorState {
  title: string;
  remediation: string;
}

export interface RelatedRouteLink {
  label: string;
  routeId: string;
  href: string;
  relationship: 'source_repo' | 'deployed_resource' | 'runtime_guard' | 'policy_rule' | 'audit_log';
}

