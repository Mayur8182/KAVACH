/**
 * Find canonical RouteContract by exact path or registered alias.
 */
export function getRouteByPath(pathname: string): RouteContract | undefined {
  if (!pathname) return undefined;
  const clean = pathname.split('?')[0].replace(/\/$/, '') || '/home';

  // Exact match
  for (const route of Object.values(CANONICAL_ROUTES)) {
    if (route.path === clean) return route;
    if (route.aliases && route.aliases.includes(clean)) return route;
  }

  // Prefix match (longest matching path)
  let bestMatch: RouteContract | undefined;
  let maxLen = 0;
  for (const route of Object.values(CANONICAL_ROUTES)) {
    if (clean.startsWith(route.path) && route.path.length > maxLen) {
      bestMatch = route;
      maxLen = route.path.length;
    }
  }
  return bestMatch;
}

/**
 * Produce authoritative breadcrumb items for any pathname.
 */
export function getBreadcrumbsForPath(pathname: string): BreadcrumbStep[] {
  const clean = pathname.split('?')[0].replace(/\/+$/, '') || '/';
  if (clean === '/home' || clean === '/') {
    return [{ label: 'Overview' }];
  }

  const route = getRouteByPath(clean);
  if (route && route.breadcrumb) {
    const steps = route.breadcrumb.filter((b) => b.label !== 'Platform');
    return steps.length > 0 ? steps : [{ label: route.navigationLabel }];
  }

  // Fallback to structured parsing
  const segments = clean.split('/').filter(Boolean);
  const steps: BreadcrumbStep[] = [];
  let accum = '';
  for (let i = 0; i < segments.length; i++) {
    accum += '/' + segments[i];
    const isLast = i === segments.length - 1;
    const label =
      segments[i].charAt(0).toUpperCase() + segments[i].slice(1).replace(/-/g, ' ');
    steps.push({
      label,
      href: isLast ? undefined : accum,
    });
  }
  return steps.length > 0 ? steps : [{ label: 'Overview' }];
}
